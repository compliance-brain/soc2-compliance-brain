#!/usr/bin/env python3
"""Work out which controls, policies, policy statements, risks and CUECs are in
scope for your company, from program/context/profile.yaml and the library.

Usage:
    python3 tools/scope.py            # print a summary and write program/controls/scope.md
    python3 tools/scope.py --quiet    # write the file only

Needs Python 3.8+ and nothing else. The rules match the Google Sheets edition
of the Compliance Brain; see brain/library/README.md.
"""
import csv
import os
import re
import sys
from datetime import date

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LIB = os.path.join(ROOT, 'brain', 'library')
PROFILE = os.path.join(ROOT, 'program', 'context', 'profile.yaml')
OUT = os.path.join(ROOT, 'program', 'controls', 'scope.md')
STAGES = ('Startup', 'Scaleup', 'Enterprise')


def split_answers(text):
    """Split a comma-separated answer, keeping commas inside brackets."""
    out, depth, cur = [], 0, ''
    for ch in text:
        depth += (ch == '(') - (ch == ')')
        if ch == ',' and depth == 0:
            out.append(cur.strip())
            cur = ''
        else:
            cur += ch
    if cur.strip():
        out.append(cur.strip())
    return out


def load_profile(path=PROFILE):
    """Read the simple 'Field: answer' format used by profile.yaml."""
    profile = {}
    with open(path, encoding='utf-8') as f:
        for line in f:
            line = line.rstrip('\n')
            if not line.strip() or line.lstrip().startswith('#'):
                continue
            key, sep, value = line.partition(':')
            if not sep:
                continue
            value = value.split(' #')[0].strip().strip('"').strip("'")
            profile[key.strip()] = value
    return profile


def read_csv(name):
    with open(os.path.join(LIB, name), encoding='utf-8', newline='') as f:
        return list(csv.DictReader(f))


def unknown(answer):
    a = (answer or '').strip()
    return a == '' or a in ('TBC', 'Unsure') or a.startswith('None') or a.startswith('{{')


def hit(values, answer):
    wanted = [v.strip() for v in values.split('|') if v.strip()]
    given = split_answers(answer or '')
    return any(w in given for w in wanted)


def passes(field, test, values, profile):
    if not field:
        return True
    answer = profile.get(field, '')
    if test == 'in use':
        return not unknown(answer)
    if test == 'not in use':
        return unknown(answer)
    if test == 'any of':
        return hit(values, answer)
    return not hit(values, answer)  # 'not any of': unanswered passes


def scope_controls(profile, controls):
    stage = profile.get('Company Stage', '')
    stage = stage if stage in STAGES else 'Startup'
    frameworks = profile.get('Framework Scope', '')
    result = []
    for c in controls:
        ok_stage = not c['Stages'] or stage in [s.strip() for s in c['Stages'].split(',')]
        ok_crit = c['Criteria'] == 'Security' or c['Criteria'] in frameworks
        ok_a = passes(c['If'], c['Is'], c['Values'], profile)
        ok_b = passes(c['And'], c['And is'], c['And values'], profile)
        if ok_stage and ok_crit and ok_a and ok_b:
            field = c['And'] if c['And is'] == 'in use' else (c['If'] if c['Is'] == 'in use' else '')
            tools = ' / '.join(split_answers(profile.get(field, ''))) if field else ''
            wording = c['Wording'].replace('{{TOOL}}', tools) if tools else c['Wording']
            result.append(dict(c, Tailored=wording))
    return result, stage


def linked_in_scope(ids, in_scope):
    return [i.strip() for i in ids.split(',') if i.strip() in in_scope]


def main():
    quiet = '--quiet' in sys.argv
    profile = load_profile()
    controls = read_csv('controls.csv')
    chosen, stage = scope_controls(profile, controls)
    ids = {c['ID'] for c in chosen}
    policies = read_csv('policies.csv')
    statements = read_csv('policy-statements.csv')
    risks = read_csv('risks.csv')

    pol_in = [p for p in policies if linked_in_scope(p['Linked controls'], ids)]
    st_in = [s for s in statements if linked_in_scope(s['Linked controls'], ids)]
    risk_in = [r for r in risks if linked_in_scope(r['Treating controls'], ids)]
    by_reason = {}
    for c in chosen:
        by_reason[c['Brought in by']] = by_reason.get(c['Brought in by'], 0) + 1
    open_high = [k for k, v in profile.items() if unknown(v)]

    lines = [
        '# Scope', '',
        f'Generated by `tools/scope.py` on {date.today().isoformat()} from '
        '[profile.yaml](../context/profile.yaml). Don\'t edit this file: change the profile and run the tool again. '
        'Your working control list, with owners and status, is [control-list.csv](control-list.csv).', '',
        '| | In scope |', '| --- | --- |',
        f'| Controls | {len(chosen)} of {len(controls)} |',
        f'| Policies | {len(pol_in)} of {len(policies)} |',
        f'| Policy statements | {len(st_in)} of {len(statements)} |',
        f'| Risks | {len(risk_in)} of {len(risks)} |', '',
        f'Stage used: **{stage}**' + ('' if profile.get('Company Stage') in STAGES else ' (Company Stage not answered, so Startup is assumed)')
        + '. Brought in by: ' + ', '.join(f'{k} {v}' for k, v in sorted(by_reason.items())) + '.', '',
    ]
    if open_high:
        lines += [f'> [!NOTE]\n> {len(open_high)} profile fields are still TBC, Unsure or blank, so scope will change '
                  'as they are answered. Run `python3 tools/check.py` to see which high-impact fields to answer first.', '']
    lines += ['## Controls', '', '| ID | Control | Wording | Frequency | Evidence | Brought in by |',
              '| --- | --- | --- | --- | --- | --- |']
    for c in chosen:
        cells = [c['ID'], c['Control'], c['Tailored'], c['Frequency'], c['Evidence'], c['Brought in by']]
        lines.append('| ' + ' | '.join(x.replace('|', '/').replace('\n', ' ') for x in cells) + ' |')
    lines += ['', '## Policies and statements', '']
    for p in pol_in:
        refs = [s['Ref'] for s in st_in if s['Policy'] == p['ID']]
        lines.append(f'- **{p["ID"]} {p["Policy"]}**: statements {", ".join(refs) or "none"}')
    out_pol = [p for p in policies if p not in pol_in]
    if out_pol:
        lines += ['', 'Not in scope: ' + ', '.join(f'{p["ID"]} {p["Policy"]}' for p in out_pol) + '.']
    lines += ['', '## Risks', '', '| ID | Category | Risk | Treating controls in scope |', '| --- | --- | --- | --- |']
    for r in risk_in:
        lines.append(f'| {r["ID"]} | {r["Category"]} | {r["Risk"]} | {", ".join(linked_in_scope(r["Treating controls"], ids))} |')
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, 'w', encoding='utf-8') as f:
        f.write('\n'.join(lines) + '\n')
    if not quiet:
        print(f'Stage: {stage}')
        print(f'Controls in scope: {len(chosen)} of {len(controls)}  ({", ".join(f"{k} {v}" for k, v in sorted(by_reason.items()))})')
        print(f'Policies in scope: {len(pol_in)} of {len(policies)}')
        print(f'Policy statements in scope: {len(st_in)} of {len(statements)}')
        print(f'Risks in scope: {len(risk_in)} of {len(risks)}')
        print(f'Wrote {os.path.relpath(OUT, ROOT)}')


if __name__ == '__main__':
    main()
